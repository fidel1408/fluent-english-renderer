// Builds audio/manifest.js from the generated clip indexes (audio/index-narr.json, audio/index-dict.json).
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
function hash(s) { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; } return h.toString(36); }
const key = (role, text) => (role || "maya") + ":" + hash(text.replace(/\s+/g, " ").trim());
const clips = {};
let n = 0;
for (const name of fs.readdirSync(path.join(root, "audio")).filter((f) => /^index-.*\.json$/.test(f)).sort()) {
  const f = path.join(root, "audio", name);
  if (!fs.existsSync(f)) continue;
  for (const e of JSON.parse(fs.readFileSync(f, "utf8"))) {
    const c = { f: e.f, d: e.d };
    if (name.startsWith("index-dict")) { c.s = e.s; c.p = 1; }
    const k = key(e.role, e.text);
    if (!clips[k]) { clips[k] = c; n++; }
  }
}
const out = 'window.FE=window.FE||{};/* Natural recorded narration (generated by tools/make-voices.py with Kokoro, an open-source neural voice; no paid service). */\n' +
  "FE.Voice=FE.Voice||{};FE.Voice.clips=Object.assign(FE.Voice.clips||{}," + JSON.stringify(clips) + ");\n";
fs.writeFileSync(path.join(root, "audio", "manifest.js"), out);
console.log("clips in manifest:", n, "bytes", out.length);
